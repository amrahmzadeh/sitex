export interface SocialIconsGroupProps {
  links: SocialLinkItem[];
  styleType?: 'circle' | 'rounded' | 'square';
  iconColor?: string;
  iconBgColor?: string;
  size?: number;
  gap?: number;
  align?: 'center' | 'flex-start' | 'flex-end';
}

export function SocialIconsGroup({
  links,
  styleType = 'circle',
  iconColor,
  iconBgColor,
  size = 44,
  gap = 12,
  align = 'center',
}: SocialIconsGroupProps) {
  if (!links || links.length === 0) return null;

  const borderRadius =
    styleType === 'circle' ? '50%' : styleType === 'rounded' ? '12px' : '6px';
  const iconInnerSize = Math.round(size * 0.52);

  return (
    <div
      style={{
        display: 'flex',
        gap,
        justifyContent: align,
        alignItems: 'center',
        flexWrap: 'wrap',
      }}
    >
      {links.map((link) => {
        const platformKey = (link.platform || '').toLowerCase().trim();
        const info = PLATFORM_INFO[platformKey] || {
          name: link.platform,
          brandColor: '#7C5CFC',
          defaultBg: '#7C5CFC',
          svg: (
            <svg viewBox="0 0 24 24" width="100%" height="100%" fill="currentColor">
              <circle cx="12" cy="12" r="10" />
            </svg>
          ),
        };

        const bg = iconBgColor || info.defaultBg;
        const color =
          iconColor || (platformKey === 'snapchat' ? '#000000' : '#FFFFFF');

        return (
          <motion.a
            key={link.platform}
            href={link.url}
            target="_blank"
            rel="noopener noreferrer"
            title={info.name}
            aria-label={info.name}
            whileHover={{ scale: 1.12, y: -3 }}
            whileTap={{ scale: 0.95 }}
            style={{
              width: size,
              height: size,
              borderRadius,
              background: bg,
              color,
              display: 'inline-flex',
              alignItems: 'center',
              justifyContent: 'center',
              textDecoration: 'none',
              boxShadow: `0 4px 14px ${info.brandColor}35`,
              border: '1px solid rgba(255, 255, 255, 0.12)',
              flexShrink: 0,
              transition: 'box-shadow 0.2s',
            }}
          >
            <span
              style={{
                width: iconInnerSize,
                height: iconInnerSize,
                display: 'inline-flex',
                alignItems: 'center',
                justifyContent: 'center',
                color: 'inherit',
              }}
            >
              {info.svg}
            </span>
          </motion.a>
        );
      })}
    </div>
  );
}
