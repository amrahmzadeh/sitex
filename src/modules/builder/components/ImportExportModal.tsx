'use client';

import React, { useState, useMemo } from 'react';
import {
  Download,
  Upload,
  Copy,
  Check,
  FileCode,
  FileJson,
  AlertTriangle,
  CheckCircle2,
  Settings,
  Eye,
} from 'lucide-react';
import { parseSTL, compileSTL } from '../../stl';
import { BuilderTemplateDocument } from '../types';

interface ImportExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  stlCode: string;
  doc: BuilderTemplateDocument;
  onImportSTL: (code: string) => void;
  onImportJSON: (jsonString: string) => void;
}

const MAX_IMPORT_SIZE = 2 * 1024 * 1024; // 2MB limit

export function ImportExportModal({
  isOpen,
  onClose,
  stlCode,
  doc,
  onImportSTL,
  onImportJSON,
}: ImportExportModalProps) {
  const [activeTab, setActiveTab] = useState<'export' | 'import'>('export');
  const [copiedType, setCopiedType] = useState<string | null>(null);
  const [importText, setImportText] = useState('');
  const [importError, setImportError] = useState<string | null>(null);
  const [importSuccess, setImportSuccess] = useState<string | null>(null);

  // Pre-import preview analysis
  const importPreview = useMemo(() => {
    const trimmed = importText.trim();
    if (!trimmed) return null;

    if (trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        return {
          type: 'JSON',
          id: parsed.id || 'Bilinmir',
          name: parsed.name || 'Ad təyin olunmayıb',
          schemaVersion: parsed.schemaVersion || 1,
          nodesCount: parsed.nodes?.length || 0,
        };
      } catch {
        return null;
      }
    }

    const { ast } = parseSTL(trimmed);
    if (ast) {
      return {
        type: 'STL',
        id: ast.id,
        name: ast.meta.name || ast.id,
        schemaVersion: 2,
        colorsCount: Object.keys(ast.colors || {}).length,
      };
    }

    return null;
  }, [importText]);

  if (!isOpen) return null;

  const handleCopySTL = () => {
    navigator.clipboard.writeText(stlCode);
    setCopiedType('stl');
    setTimeout(() => setCopiedType(null), 2000);
  };

  const handleCopyJSON = () => {
    const payload = { ...doc, schemaVersion: 2 };
    navigator.clipboard.writeText(JSON.stringify(payload, null, 2));
    setCopiedType('json');
    setTimeout(() => setCopiedType(null), 2000);
  };

  const handleDownloadSTL = () => {
    const blob = new Blob([stlCode], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${doc.slug || 'theme'}.stl`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadJSON = () => {
    const payload = { ...doc, schemaVersion: 2 };
    const blob = new Blob([JSON.stringify(payload, null, 2)], {
      type: 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${doc.slug || 'theme'}.sitex-theme.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadTailwind = () => {
    const { ast } = parseSTL(stlCode);
    const compiled = ast ? compileSTL(ast) : null;
    const tailwindCode = `// Generated by SiteX Theme Language Compiler
module.exports = ${JSON.stringify(compiled?.tailwindConfig || {}, null, 2)};\n`;
    const blob = new Blob([tailwindCode], { type: 'text/javascript;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `tailwind.theme.config.js`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleImportSubmit = () => {
    setImportError(null);
    setImportSuccess(null);
    const trimmed = importText.trim();

    if (!trimmed) {
      setImportError('Zəhmət olmasa STL kodu və ya JSON mətni daxil edin.');
      return;
    }

    if (new Blob([trimmed]).size > MAX_IMPORT_SIZE) {
      setImportError('Fayl ölçüsü limiti aşıldı! Maksimum icazə verilən həcm 2MB-dır.');
      return;
    }

    if (trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        if (!parsed.id) {
          throw new Error('JSON faylında tələb olunan "id" xassəsi tapılmadı.');
        }

        // Schema Version check and auto-migration
        if (!parsed.schemaVersion || parsed.schemaVersion < 2) {
          parsed.schemaVersion = 2;
          parsed.updatedAt = new Date().toISOString();
        }

        onImportJSON(JSON.stringify(parsed));
        setImportSuccess('JSON şablonu uğurla təhlil edildi və miqrasiya ilə idxal olundu!');
        setTimeout(() => onClose(), 1200);
      } catch (err: any) {
        setImportError(`JSON format xətası: ${err.message}`);
      }
      return;
    }

    // Try STL
    const { ast, errors } = parseSTL(trimmed);
    const fatalErrors = errors.filter((e) => e.severity === 'error');
    if (fatalErrors.length > 0) {
      setImportError(
        `STL Sintaksis xətası: ${fatalErrors[0].message} (Sətir: ${fatalErrors[0].line})`
      );
      return;
    }

    onImportSTL(trimmed);
    setImportSuccess('STL tema kodu uğurla təsdiqləndi və idxal edildi!');
    setTimeout(() => onClose(), 1200);
  };

  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    if (file.size > MAX_IMPORT_SIZE) {
      setImportError('Fayl ölçüsü 2MB-dan böyük ola bilməz.');
      return;
    }

    const reader = new FileReader();
    reader.onload = (event) => {
      const content = event.target?.result as string;
      setImportText(content);
    };
    reader.readAsText(file);
  };

  return (
    <div
      style={{
        position: 'fixed',
        inset: 0,
        background: 'rgba(0,0,0,0.75)',
        backdropFilter: 'blur(5px)',
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        zIndex: 2000,
      }}
      onClick={onClose}
    >
      <div
        style={{
          width: 580,
          background: '#16181E',
          borderRadius: 16,
          border: '1px solid #282C35',
          boxShadow: '0 25px 70px rgba(0,0,0,0.7)',
          overflow: 'hidden',
          display: 'flex',
          flexDirection: 'column',
        }}
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div
          style={{
            padding: '20px 24px',
            borderBottom: '1px solid #252932',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
          }}
        >
          <div style={{ display: 'flex', gap: 12 }}>
            <button
              type="button"
              onClick={() => setActiveTab('export')}
              style={{
                display: 'flex',
                alignItems: 'center',
                gap: 6,
                padding: '8px 16px',
                borderRadius: 8,
                border: activeTab === 'export' ? '1px solid #00D37D' : '1px solid transparent',
                background: activeTab === 'export' ? 'rgba(0,211,125,0.12)' : 'transparent',
                color: activeTab === 'export' ? '#00D37D' : '#8888A0',
                fontSize: 13,
                fontWeight: 700,
                cursor: 'pointer',
              }}
            >
              <Download size={15} />
              İxrac Et (Export)
            </button>
            <button
              type="button"
              onClick={() => setActiveTab('import')}
              style={{
                display: 'flex',
                alignItems: 'center',
                gap: 6,
                padding: '8px 16px',
                borderRadius: 8,
                border: activeTab === 'import' ? '1px solid #00D37D' : '1px solid transparent',
                background: activeTab === 'import' ? 'rgba(0,211,125,0.12)' : 'transparent',
                color: activeTab === 'import' ? '#00D37D' : '#8888A0',
                fontSize: 13,
                fontWeight: 700,
                cursor: 'pointer',
              }}
            >
              <Upload size={15} />
              İdxal Et (Import)
            </button>
          </div>

          <button
            type="button"
            onClick={onClose}
            style={{
              background: 'transparent',
              border: 'none',
              color: '#8888A0',
              cursor: 'pointer',
              fontSize: 18,
            }}
          >
            ✕
          </button>
        </div>

        {/* Modal Body */}
        <div style={{ padding: 24 }}>
          {activeTab === 'export' ? (
            <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
              {/* STL Export Box */}
              <div
                style={{
                  padding: 16,
                  borderRadius: 12,
                  background: '#121418',
                  border: '1px solid #22262E',
                }}
              >
                <div
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'space-between',
                    marginBottom: 10,
                  }}
                >
                  <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                    <FileCode size={18} color="#00D37D" />
                    <div>
                      <h4 style={{ margin: 0, fontSize: 13, fontWeight: 700, color: '#FFF' }}>
                        SiteX Theme Language (.stl)
                      </h4>
                      <span style={{ fontSize: 11, color: '#8888A0' }}>
                        Deklarativ və təmiz mövzu kodu
                      </span>
                    </div>
                  </div>
                  <div style={{ display: 'flex', gap: 8 }}>
                    <button
                      type="button"
                      onClick={handleCopySTL}
                      style={{
                        padding: '6px 12px',
                        borderRadius: 6,
                        border: '1px solid #282C35',
                        background: '#181A20',
                        color: copiedType === 'stl' ? '#00D37D' : '#FFF',
                        fontSize: 11,
                        cursor: 'pointer',
                        display: 'flex',
                        alignItems: 'center',
                        gap: 6,
                      }}
                    >
                      {copiedType === 'stl' ? <Check size={13} /> : <Copy size={13} />}
                      {copiedType === 'stl' ? 'Kopyalandı' : 'Kopyala'}
                    </button>
                    <button
                      type="button"
                      onClick={handleDownloadSTL}
                      style={{
                        padding: '6px 12px',
                        borderRadius: 6,
                        border: 'none',
                        background: '#00D37D',
                        color: '#000',
                        fontSize: 11,
                        fontWeight: 700,
                        cursor: 'pointer',
                        display: 'flex',
                        alignItems: 'center',
                        gap: 6,
                      }}
                    >
                      <Download size={13} />
                      Yüklə
                    </button>
                  </div>
                </div>
              </div>

              {/* JSON Export Box */}
              <div
                style={{
                  padding: 16,
                  borderRadius: 12,
                  background: '#121418',
                  border: '1px solid #22262E',
                }}
              >
                <div
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'space-between',
                    marginBottom: 10,
                  }}
                >
                  <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                    <FileJson size={18} color="#3B82F6" />
                    <div>
                      <h4 style={{ margin: 0, fontSize: 13, fontWeight: 700, color: '#FFF' }}>
                        SiteX Template JSON (.sitex-theme.json)
                      </h4>
                      <span style={{ fontSize: 11, color: '#8888A0' }}>
                        Bütün seksiyalar və tokenlər (Schema v2)
                      </span>
                    </div>
                  </div>
                  <div style={{ display: 'flex', gap: 8 }}>
                    <button
                      type="button"
                      onClick={handleCopyJSON}
                      style={{
                        padding: '6px 12px',
                        borderRadius: 6,
                        border: '1px solid #282C35',
                        background: '#181A20',
                        color: copiedType === 'json' ? '#00D37D' : '#FFF',
                        fontSize: 11,
                        cursor: 'pointer',
                        display: 'flex',
                        alignItems: 'center',
                        gap: 6,
                      }}
                    >
                      {copiedType === 'json' ? <Check size={13} /> : <Copy size={13} />}
                      {copiedType === 'json' ? 'Kopyalandı' : 'Kopyala'}
                    </button>
                    <button
                      type="button"
                      onClick={handleDownloadJSON}
                      style={{
                        padding: '6px 12px',
                        borderRadius: 6,
                        border: 'none',
                        background: '#3B82F6',
                        color: '#FFF',
                        fontSize: 11,
                        fontWeight: 700,
                        cursor: 'pointer',
                        display: 'flex',
                        alignItems: 'center',
                        gap: 6,
                      }}
                    >
                      <Download size={13} />
                      Yüklə
                    </button>
                  </div>
                </div>
              </div>

              {/* Tailwind Config Export Box */}
              <div
                style={{
                  padding: 16,
                  borderRadius: 12,
                  background: '#121418',
                  border: '1px solid #22262E',
                  display: 'flex',
                  alignItems: 'center',
                  justifyContent: 'space-between',
                }}
              >
                <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                  <Settings size={18} color="#A855F7" />
                  <div>
                    <h4 style={{ margin: 0, fontSize: 13, fontWeight: 700, color: '#FFF' }}>
                      Tailwind Config (.js)
                    </h4>
                    <span style={{ fontSize: 11, color: '#8888A0' }}>
                      Layihənizdə birbaşa Tailwind ilə istifadə üçün
                    </span>
                  </div>
                </div>
                <button
                  type="button"
                  onClick={handleDownloadTailwind}
                  style={{
                    padding: '6px 12px',
                    borderRadius: 6,
                    border: 'none',
                    background: '#A855F7',
                    color: '#FFF',
                    fontSize: 11,
                    fontWeight: 700,
                    cursor: 'pointer',
                    display: 'flex',
                    alignItems: 'center',
                    gap: 6,
                  }}
                >
                  <Download size={13} />
                  Yüklə
                </button>
              </div>
            </div>
          ) : (
            <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
              <div>
                <label
                  style={{ display: 'block', fontSize: 12, color: '#8888A0', marginBottom: 6 }}
                >
                  Fayl yükləyin (.stl və ya .json, maks 2MB):
                </label>
                <input
                  type="file"
                  accept=".stl,.json"
                  onChange={handleFileUpload}
                  style={{ fontSize: 12, color: '#FFF' }}
                />
              </div>

              <textarea
                rows={6}
                placeholder="Və ya STL kodunu / JSON məzmununu buraya yapışdırın..."
                value={importText}
                onChange={(e) => setImportText(e.target.value)}
                style={{
                  width: '100%',
                  padding: 12,
                  borderRadius: 8,
                  background: '#101216',
                  border: '1px solid #282C35',
                  color: '#FFF',
                  fontSize: 12,
                  fontFamily: 'monospace',
                  resize: 'none',
                }}
              />

              {/* Pre-import summary pill */}
              {importPreview && (
                <div
                  style={{
                    padding: '8px 12px',
                    borderRadius: 6,
                    background: 'rgba(0,211,125,0.08)',
                    border: '1px solid rgba(0,211,125,0.2)',
                    fontSize: 11,
                    color: '#00D37D',
                    display: 'flex',
                    alignItems: 'center',
                    gap: 8,
                  }}
                >
                  <Eye size={13} />
                  <span>
                    Aşkarlandı: {importPreview.type} | Tema: {importPreview.name} | Versiya:{' '}
                    {importPreview.schemaVersion}
                  </span>
                </div>
              )}

              {importError && (
                <div
                  style={{
                    padding: '8px 12px',
                    borderRadius: 6,
                    background: 'rgba(239,68,68,0.1)',
                    border: '1px solid rgba(239,68,68,0.2)',
                    color: '#F87171',
                    fontSize: 12,
                    display: 'flex',
                    alignItems: 'center',
                    gap: 6,
                  }}
                >
                  <AlertTriangle size={14} />
                  <span>{importError}</span>
                </div>
              )}

              {importSuccess && (
                <div
                  style={{
                    padding: '8px 12px',
                    borderRadius: 6,
                    background: 'rgba(0,211,125,0.1)',
                    border: '1px solid rgba(0,211,125,0.2)',
                    color: '#00D37D',
                    fontSize: 12,
                    display: 'flex',
                    alignItems: 'center',
                    gap: 6,
                  }}
                >
                  <CheckCircle2 size={14} />
                  <span>{importSuccess}</span>
                </div>
              )}

              <button
                type="button"
                onClick={handleImportSubmit}
                style={{
                  width: '100%',
                  padding: '12px',
                  borderRadius: 8,
                  background: '#00D37D',
                  color: '#000',
                  border: 'none',
                  fontSize: 13,
                  fontWeight: 700,
                  cursor: 'pointer',
                  display: 'flex',
                  alignItems: 'center',
                  justifyContent: 'center',
                  gap: 8,
                }}
              >
                <Upload size={15} />
                Yoxla və İdxal Et
              </button>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
