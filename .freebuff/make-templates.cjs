const manifest = {
  schemaVersion: 1,
  defaults: { repository: OWNER_REPO, ref: REF, manifestPath: 'manifest.json' },
  templates: templates.map((t) => ({
    id: t.id,
    name: t.name,
    description: t.description,
    category: t.category,
    subcategory: t.subcategory,
    version: '1.0.0',
    themePreset: t.themePreset,
    preview: { gradient: t.preview },
    source: { path: `templates/${t.id}`, ref: REF },
  })),
};

fs.writeFileSync(
  path.join(OUT, 'manifest.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
  'utf8'
);

for (const t of templates) {
  const dir = path.join(OUT, 'templates', t.id);
  fs.mkdirSync(dir, { recursive: true });
  const pkg = {
    id: t.id,
    name: t.name,
    version: '1.0.0',
    themePreset: t.themePreset,
    theme: t.theme,
  };
  fs.writeFileSync(path.join(dir, 'template.json'), `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');
  fs.writeFileSync(
    path.join(dir, 'README.md'),
    `# ${t.name}\n\n${t.description}\n\n- Kateqoriya: \`${t.category}\`\n- Alt kateqoriya: \`${t.subcategory}\`\n- Versiya: 1.0.0\n\nTema dəyərləri \`template.json\` faylındadır; Applayış yalnız icazəli skalyar tema açarlarını tətbiq edir.\n`,
    'utf8'
  );
}

